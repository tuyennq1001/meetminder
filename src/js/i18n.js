let currentLocale = 'en';

function interpolate(value, vars = {}) {
    return String(value).replace(/\{\{(\w+)\}\}/g, (_, key) => String(vars[key] ?? ''));
}

export function normalizeLocale(locale) {
    return Object.prototype.hasOwnProperty.call(LOCALES, locale) ? locale : 'en';
}

export function getCurrentLocale() {
    return currentLocale;
}

export function t(key, vars = {}) {
    const dictionary = LOCALES[currentLocale] || LOCALES.en;
    const fallback = LOCALES.en[key] ?? LOCALES.vi[key] ?? key;
    return interpolate(dictionary[key] ?? fallback, vars);
}

export function applyLocale(locale = currentLocale) {
    currentLocale = normalizeLocale(locale);
    document.documentElement.lang = currentLocale;
    document.documentElement.dataset.locale = currentLocale;

    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const value = t(element.dataset.i18n);
        if (element.dataset.i18nHtml === 'true') element.innerHTML = value;
        else element.textContent = value;
    });
    document.querySelectorAll('[data-i18n-title]').forEach((element) => {
        element.title = t(element.dataset.i18nTitle);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
        element.placeholder = t(element.dataset.i18nPlaceholder);
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
        element.setAttribute('aria-label', t(element.dataset.i18nAriaLabel));
    });
}
